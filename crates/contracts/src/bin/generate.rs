use spiling_contracts::{
    ArtifactView, Hello, MAX_BINARY_BYTES, MAX_CONTROL_BYTES, OperationView, TRIANGLE_HEADER_BYTES,
    TRIANGLE_INDEX_COUNT, TRIANGLE_SCHEMA_VERSION, TRIANGLE_VERTEX_COUNT,
};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args: Vec<_> = env::args().skip(1).collect();
    if !args.is_empty() && args != ["--check"] {
        return Err("usage: generate [--check]".into());
    }
    let config = ts_rs::Config::default();
    let mut output = String::from(
        "/*!\n * SPDX-FileCopyrightText: 2026 Spiling contributors\n * SPDX-License-Identifier: OSL-3.0\n * Licensed under the Open Software License version 3.0\n */\n\n// Generated by spiling-contracts; do not edit.\n\n",
    );
    for declaration in [
        ArtifactView::decl(&config),
        Hello::decl(&config),
        OperationView::decl(&config),
    ] {
        output.push_str("export ");
        output.push_str(&declaration);
        output.push_str("\n\n");
    }
    for (name, value) in [
        ("MAX_CONTROL_BYTES", u64::from(MAX_CONTROL_BYTES)),
        ("MAX_BINARY_BYTES", u64::from(MAX_BINARY_BYTES)),
        (
            "TRIANGLE_SCHEMA_VERSION",
            u64::from(TRIANGLE_SCHEMA_VERSION),
        ),
        ("TRIANGLE_HEADER_BYTES", TRIANGLE_HEADER_BYTES as u64),
        ("TRIANGLE_VERTEX_COUNT", u64::from(TRIANGLE_VERTEX_COUNT)),
        ("TRIANGLE_INDEX_COUNT", u64::from(TRIANGLE_INDEX_COUNT)),
    ] {
        output.push_str(&format!("export const {name} = {value} as const;\n"));
    }
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/protocol/src/generated.ts");
    if args == ["--check"] {
        if fs::read_to_string(&path)? != output {
            return Err(
                "generated protocol drift; run cargo run -p spiling-contracts --bin generate"
                    .into(),
            );
        }
    } else {
        fs::create_dir_all(path.parent().ok_or("generated path has no parent")?)?;
        fs::write(path, output)?;
    }
    Ok(())
}
