#[derive(Default)]
struct Declarations {
    config: ts_rs::Config,
    visited: HashSet<TypeId>,
    types: BTreeMap<String, (&'static str, String)>,
    error: Option<String>,
}

impl Declarations {
    fn finish(self) -> Result<Vec<String>, String> {
        if let Some(error) = self.error {
            return Err(error);
        }
        Ok(self
            .types
            .into_values()
            .map(|(_, declaration)| declaration)
            .collect())
    }
}

impl TypeVisitor for Declarations {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if self.error.is_some() || !self.visited.insert(TypeId::of::<T>()) {
            return;
        }
        if T::output_path().is_some() {
            let name = T::ident(&self.config);
            let declaration = T::decl(&self.config);
            if let Some((previous_type, previous_declaration)) = self.types.get(&name) {
                if previous_declaration != &declaration {
                    self.error = Some(format!(
                        "conflicting TypeScript name {name}: {previous_type} and {}",
                        type_name::<T>()
                    ));
                    return;
                }
            } else {
                self.types.insert(name, (type_name::<T>(), declaration));
            }
        }
        T::visit_generics(self);
        T::visit_dependencies(self);
    }
}

