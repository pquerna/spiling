#[cfg(test)]
#[allow(dead_code)]
mod declaration_tests {
    use super::*;

    #[derive(TS)]
    struct Shared {
        value: String,
    }

    #[derive(TS)]
    struct Generic<Value> {
        value: Value,
    }

    #[derive(TS)]
    struct Nested {
        values: Option<Vec<BTreeMap<String, Box<Shared>>>>,
    }

    #[derive(TS)]
    struct Recursive {
        next: Option<Box<Recursive>>,
        shared: Shared,
    }

    #[derive(TS)]
    #[ts(rename = "Shared")]
    struct Conflicting {
        other: bool,
    }

    #[test]
    fn closes_nested_shared_and_recursive_dependencies_once() {
        let mut declarations = Declarations::default();
        declarations.visit::<Nested>();
        assert_eq!(
            declarations
                .types
                .keys()
                .map(String::as_str)
                .collect::<Vec<_>>(),
            ["Nested", "Shared"]
        );
        declarations.visit::<Recursive>();
        declarations.visit::<Shared>();
        let declarations = declarations.finish().unwrap();
        let names: Vec<_> = declarations
            .iter()
            .map(|declaration| declaration.split_whitespace().nth(1).unwrap())
            .collect();
        assert_eq!(names, ["Nested", "Recursive", "Shared"]);
        let mut reversed = Declarations::default();
        reversed.visit::<Recursive>();
        reversed.visit::<Nested>();
        assert_eq!(declarations, reversed.finish().unwrap());
    }

    #[test]
    fn rejects_conflicting_global_names() {
        let mut declarations = Declarations::default();
        declarations.visit::<Shared>();
        declarations.visit::<Conflicting>();
        let error = declarations.finish().unwrap_err();
        assert!(error.contains("Shared"));
        assert!(error.contains("Conflicting"));
    }

    #[test]
    fn deduplicates_generic_declarations_without_losing_arguments() {
        let mut declarations = Declarations::default();
        declarations.visit::<Generic<String>>();
        declarations.visit::<Generic<Shared>>();
        let declarations = declarations.finish().unwrap();
        assert_eq!(declarations.len(), 2);
        assert!(declarations[0].starts_with("type Generic<Value>"));
        assert!(declarations[1].starts_with("type Shared"));
    }
}
